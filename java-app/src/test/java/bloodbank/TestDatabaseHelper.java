package bloodbank;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public class TestDatabaseHelper {

    private static final String H2_URL = "jdbc:h2:mem:bloodbank_test;MODE=Oracle;DEFAULT_NULL_ORDERING=HIGH;DB_CLOSE_DELAY=-1";
    private static Connection sharedConnection;

    public static synchronized void initTestDatabase() throws SQLException {
        if (sharedConnection == null || sharedConnection.isClosed()) {
            sharedConnection = DriverManager.getConnection(H2_URL, "sa", "");
            DBConnection.setCustomConnectionSupplier(() -> {
                try {
                    return DriverManager.getConnection(H2_URL, "sa", "");
                } catch (SQLException e) {
                    throw new RuntimeException("Could not create test connection", e);
                }
            });
        }

        try (Statement s = sharedConnection.createStatement()) {
            // Drop existing tables cleanly
            s.execute("DROP TABLE IF EXISTS ALLOCATION_DISPATCH CASCADE");
            s.execute("DROP TABLE IF EXISTS EMERGENCY_REQUEST CASCADE");
            s.execute("DROP TABLE IF EXISTS BLOOD_INVENTORY CASCADE");
            s.execute("DROP TABLE IF EXISTS DONATION_RECORD CASCADE");
            s.execute("DROP TABLE IF EXISTS HOSPITAL CASCADE");
            s.execute("DROP TABLE IF EXISTS DONOR CASCADE");

            // Create schema matching 01_schema.sql
            s.execute("""
                CREATE TABLE DONOR (
                    Donor_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    First_Name VARCHAR2(50) NOT NULL,
                    Last_Name VARCHAR2(50) NOT NULL,
                    Blood_Type VARCHAR2(3) NOT NULL,
                    DOB DATE NOT NULL,
                    Gender CHAR(1),
                    Contact_Number VARCHAR2(15) UNIQUE NOT NULL,
                    Email VARCHAR2(100) UNIQUE,
                    Address VARCHAR2(255) NOT NULL,
                    Last_Donation_Date DATE,
                    Eligibility_Status VARCHAR2(30) DEFAULT 'Eligible'
                )
            """);

            s.execute("""
                CREATE TABLE HOSPITAL (
                    Hospital_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    Hospital_Name VARCHAR2(100) NOT NULL,
                    License_Number VARCHAR2(50) UNIQUE NOT NULL,
                    Address VARCHAR2(255) NOT NULL,
                    City VARCHAR2(50) NOT NULL,
                    Contact_Person VARCHAR2(50) NOT NULL,
                    Phone_Number VARCHAR2(15) NOT NULL,
                    Email VARCHAR2(100)
                )
            """);

            s.execute("""
                CREATE TABLE DONATION_RECORD (
                    Donation_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    Donor_ID NUMBER NOT NULL REFERENCES DONOR(Donor_ID),
                    Donation_Date DATE DEFAULT CURRENT_DATE NOT NULL,
                    Hemoglobin_Level NUMBER(4,2),
                    Blood_Pressure VARCHAR2(20),
                    Pulse_Rate NUMBER,
                    Medical_Screening_Result VARCHAR2(50) DEFAULT 'Passed'
                )
            """);

            s.execute("""
                CREATE TABLE BLOOD_INVENTORY (
                    Unit_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    Donation_ID NUMBER NOT NULL REFERENCES DONATION_RECORD(Donation_ID),
                    Blood_Type VARCHAR2(3) NOT NULL,
                    Component_Type VARCHAR2(50) NOT NULL,
                    Volume_ML NUMBER NOT NULL,
                    Collection_Date DATE NOT NULL,
                    Expiry_Date DATE NOT NULL,
                    Status VARCHAR2(20) DEFAULT 'Available'
                )
            """);

            s.execute("""
                CREATE TABLE EMERGENCY_REQUEST (
                    Request_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    Hospital_ID NUMBER NOT NULL REFERENCES HOSPITAL(Hospital_ID),
                    Required_Blood_Type VARCHAR2(3) NOT NULL,
                    Required_Component VARCHAR2(50) NOT NULL,
                    Units_Requested NUMBER NOT NULL,
                    Urgency_Level VARCHAR2(20) NOT NULL,
                    Request_Timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                    Request_Status VARCHAR2(20) DEFAULT 'Pending'
                )
            """);

            s.execute("""
                CREATE TABLE ALLOCATION_DISPATCH (
                    Dispatch_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    Request_ID NUMBER NOT NULL REFERENCES EMERGENCY_REQUEST(Request_ID),
                    Unit_ID NUMBER UNIQUE NOT NULL REFERENCES BLOOD_INVENTORY(Unit_ID),
                    Dispatch_Timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                    Delivery_Status VARCHAR2(20) DEFAULT 'In Transit'
                )
            """);
        }
    }

    public static synchronized void resetTestDatabase() throws SQLException {
        initTestDatabase();
    }

    public static synchronized void teardown() {
        DBConnection.resetCustomConnectionSupplier();
        if (sharedConnection != null) {
            try {
                sharedConnection.close();
            } catch (SQLException ignored) {
            }
            sharedConnection = null;
        }
    }
}
