-- Drop existing tables to allow clean re-runs
BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE ALLOCATION_DISPATCH CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE EMERGENCY_REQUEST CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE BLOOD_INVENTORY CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE DONATION_RECORD CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE HOSPITAL CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE DONOR CASCADE CONSTRAINTS';
EXCEPTION
   WHEN OTHERS THEN
      IF SQLCODE != -942 THEN
         RAISE;
      END IF;
END;
/

-- 1. DONOR Table
CREATE TABLE DONOR (
    Donor_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    First_Name VARCHAR2(50) NOT NULL,
    Last_Name VARCHAR2(50) NOT NULL,
    Blood_Type VARCHAR2(3) NOT NULL,
    DOB DATE NOT NULL,
    Gender CHAR(1) CHECK (Gender IN ('M', 'F', 'O')),
    Contact_Number VARCHAR2(15) UNIQUE NOT NULL,
    Email VARCHAR2(100) UNIQUE,
    Address VARCHAR2(255),
    Last_Donation_Date DATE,
    Eligibility_Status VARCHAR2(20) DEFAULT 'Eligible'
);

-- 2. HOSPITAL Table
CREATE TABLE HOSPITAL (
    Hospital_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Hospital_Name VARCHAR2(100) NOT NULL,
    License_Number VARCHAR2(50) UNIQUE NOT NULL,
    Street VARCHAR2(100),
    City VARCHAR2(50),
    Contact_Person VARCHAR2(50),
    Phone_Number VARCHAR2(15) NOT NULL,
    Email VARCHAR2(100)
);

-- 3. DONATION_RECORD Table
CREATE TABLE DONATION_RECORD (
    Donation_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Donor_ID NUMBER NOT NULL REFERENCES DONOR(Donor_ID),
    Donation_Date DATE DEFAULT SYSDATE,
    Hemoglobin_Level NUMBER(4,2) CHECK (Hemoglobin_Level >= 12.5),
    Blood_Pressure VARCHAR2(20),
    Pulse_Rate NUMBER,
    Medical_Screening_Result VARCHAR2(50)
);

-- 4. BLOOD_INVENTORY Table
CREATE TABLE BLOOD_INVENTORY (
    Unit_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Donation_ID NUMBER NOT NULL REFERENCES DONATION_RECORD(Donation_ID),
    Blood_Type VARCHAR2(3) NOT NULL,
    Component_Type VARCHAR2(50) NOT NULL,
    Volume_ML NUMBER NOT NULL,
    Collection_Date DATE NOT NULL,
    Expiry_Date DATE NOT NULL,
    Status VARCHAR2(20) DEFAULT 'Available' CHECK (Status IN ('Available', 'Reserved', 'Dispatched', 'Discarded'))
);

-- 5. EMERGENCY_REQUEST Table
CREATE TABLE EMERGENCY_REQUEST (
    Request_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Hospital_ID NUMBER NOT NULL REFERENCES HOSPITAL(Hospital_ID),
    Required_Blood_Type VARCHAR2(3) NOT NULL,
    Required_Component VARCHAR2(50) NOT NULL,
    Units_Requested NUMBER CHECK (Units_Requested > 0),
    Urgency_Level VARCHAR2(20) CHECK (Urgency_Level IN ('Critical', 'Urgent', 'Routine')),
    Request_Timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Request_Status VARCHAR2(20) DEFAULT 'Pending' CHECK (Request_Status IN ('Pending', 'Fulfilled', 'Cancelled'))
);

-- 6. ALLOCATION_DISPATCH Table
CREATE TABLE ALLOCATION_DISPATCH (
    Dispatch_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Request_ID NUMBER NOT NULL REFERENCES EMERGENCY_REQUEST(Request_ID),
    Unit_ID NUMBER UNIQUE NOT NULL REFERENCES BLOOD_INVENTORY(Unit_ID),
    Dispatch_Timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Delivery_Status VARCHAR2(20) DEFAULT 'In Transit'
);
