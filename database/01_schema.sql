-- 1. DONOR Table
CREATE TABLE DONOR (
    Donor_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    First_Name VARCHAR2(50) NOT NULL,
    Last_Name VARCHAR2(50) NOT NULL,
    Blood_Type VARCHAR2(3) NOT NULL CHECK (Blood_Type IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')),
    DOB DATE NOT NULL,
    Gender CHAR(1) CHECK (Gender IN ('M', 'F', 'O')),
    Contact_Number VARCHAR2(15) UNIQUE NOT NULL,
    Email VARCHAR2(100) UNIQUE,
    Address VARCHAR2(255) NOT NULL,
    Last_Donation_Date DATE,
    Eligibility_Status VARCHAR2(30) DEFAULT 'Eligible' CHECK (Eligibility_Status IN ('Eligible', 'Cooldown', 'Temporary_Deferral', 'Permanent_Deferral'))
);

-- 2. HOSPITAL Table
-- Standardized on Address column to match Java model, DAO, and controller definitions
CREATE TABLE HOSPITAL (
    Hospital_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Hospital_Name VARCHAR2(100) NOT NULL,
    License_Number VARCHAR2(50) UNIQUE NOT NULL,
    Address VARCHAR2(255) NOT NULL,
    City VARCHAR2(50) NOT NULL,
    Contact_Person VARCHAR2(50) NOT NULL,
    Phone_Number VARCHAR2(15) NOT NULL,
    Email VARCHAR2(100)
);

-- 3. DONATION_RECORD Table
CREATE TABLE DONATION_RECORD (
    Donation_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Donor_ID NUMBER NOT NULL REFERENCES DONOR(Donor_ID),
    Donation_Date DATE DEFAULT SYSDATE NOT NULL,
    Hemoglobin_Level NUMBER(4,2) CHECK (Hemoglobin_Level >= 12.5),
    Blood_Pressure VARCHAR2(20),
    Pulse_Rate NUMBER CHECK (Pulse_Rate > 0),
    Medical_Screening_Result VARCHAR2(50) DEFAULT 'Passed' CHECK (Medical_Screening_Result IN ('Passed', 'Failed'))
);

-- 4. BLOOD_INVENTORY Table
CREATE TABLE BLOOD_INVENTORY (
    Unit_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Donation_ID NUMBER NOT NULL REFERENCES DONATION_RECORD(Donation_ID),
    Blood_Type VARCHAR2(3) NOT NULL CHECK (Blood_Type IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')),
    Component_Type VARCHAR2(50) NOT NULL CHECK (Component_Type IN ('Whole Blood', 'Red Blood Cells', 'Packed Red Cells', 'Platelets', 'Fresh Frozen Plasma', 'Plasma')),
    Volume_ML NUMBER NOT NULL CHECK (Volume_ML > 0),
    Collection_Date DATE NOT NULL,
    Expiry_Date DATE NOT NULL,
    Status VARCHAR2(20) DEFAULT 'Available' CHECK (Status IN ('Available', 'Reserved', 'Dispatched', 'Discarded')),
    CONSTRAINT chk_unit_dates CHECK (Expiry_Date >= Collection_Date)
);

-- 5. EMERGENCY_REQUEST Table
-- Includes 'Partially_Fulfilled' to maintain 100% consistency with Java RequestService & MatchingService
CREATE TABLE EMERGENCY_REQUEST (
    Request_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Hospital_ID NUMBER NOT NULL REFERENCES HOSPITAL(Hospital_ID),
    Required_Blood_Type VARCHAR2(3) NOT NULL CHECK (Required_Blood_Type IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')),
    Required_Component VARCHAR2(50) NOT NULL CHECK (Required_Component IN ('Whole Blood', 'Red Blood Cells', 'Packed Red Cells', 'Platelets', 'Fresh Frozen Plasma', 'Plasma')),
    Units_Requested NUMBER NOT NULL CHECK (Units_Requested > 0),
    Urgency_Level VARCHAR2(20) NOT NULL CHECK (Urgency_Level IN ('Critical', 'Urgent', 'Routine')),
    Request_Timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    Request_Status VARCHAR2(20) DEFAULT 'Pending' CHECK (Request_Status IN ('Pending', 'Partially_Fulfilled', 'Fulfilled', 'Cancelled'))
);

-- 6. ALLOCATION_DISPATCH Table
CREATE TABLE ALLOCATION_DISPATCH (
    Dispatch_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Request_ID NUMBER NOT NULL REFERENCES EMERGENCY_REQUEST(Request_ID),
    Unit_ID NUMBER UNIQUE NOT NULL REFERENCES BLOOD_INVENTORY(Unit_ID),
    Dispatch_Timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    Delivery_Status VARCHAR2(20) DEFAULT 'In Transit' CHECK (Delivery_Status IN ('In Transit', 'Delivered', 'Cancelled'))
);

-- =======================================================================
-- INDEXES FOR FOREIGN KEYS & HIGH-FREQUENCY QUERIES
-- =======================================================================
CREATE INDEX idx_donor_blood_type ON DONOR(Blood_Type);
CREATE INDEX idx_donation_donor ON DONATION_RECORD(Donor_ID);
CREATE INDEX idx_inventory_lookup ON BLOOD_INVENTORY(Blood_Type, Component_Type, Status, Expiry_Date);
CREATE INDEX idx_request_hosp ON EMERGENCY_REQUEST(Hospital_ID);
CREATE INDEX idx_request_status ON EMERGENCY_REQUEST(Request_Status);
CREATE INDEX idx_dispatch_req ON ALLOCATION_DISPATCH(Request_ID);
